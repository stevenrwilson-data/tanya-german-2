/* Plurals.

   German plurals look random and mostly are not. Five endings cover almost
   everything, and which one a noun takes is largely predictable from its
   gender and its ending — feminine nouns in -e take -n without exception,
   -ung and -heit take -en, masculine nouns in -er and -el usually take
   nothing at all. Learning the five patterns beats learning 166 words.

   Which is also the design of the game: sort nouns into their pattern
   first, produce the form second.

   One thing worth telling her plainly: in the plural, gender disappears.
   Every plural noun is die, no exceptions. After the der/die/das game that
   is a genuine relief.

   pattern
     e      -e                der Tisch    -> die Tische
     ue     umlaut and -e     der Kopf     -> die Köpfe
     er     -er               das Gesicht  -> die Gesichter
     uer    umlaut and -er    das Handtuch -> die Handtücher
     n      -n                die Tasche   -> die Taschen
     en     -en               die Wohnung  -> die Wohnungen
     s      -s                das Handy    -> die Handys
     same   no change         der Löffel   -> die Löffel
     usame  umlaut only       der Apfel    -> die Äpfel
     odd    irregular         der Rhythmus -> die Rhythmen
     none   no plural at all  die Milch, das Wasser, die Musik

   Mass nouns are kept rather than dropped: 'this word has no plural' is
   itself worth knowing, and she will otherwise try to make one. */

