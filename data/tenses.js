/* Three tenses of the same verb, for the sorting conveyor.

   Ninety verbs, two hundred and seventy cards. Each verb gets one sentence
   in each tense, all three about the same situation, so a completed trio
   reads as one thing happening across time.

   The time word is stored apart from the rest of the sentence. That is
   what lets one set of content drive three difficulty levels: show it,
   swap it for something vaguer, or hide it and make her sort on the verb
   alone. It was written inline and lifted out here.

   Every future uses werden. German normally says the future with the
   present plus a time word — morgen arbeite ich — and that is the commoner
   form, but it means present and future share a verb form and the card
   becomes unsortable once the time word is gone. The grammar page teaches
   the honest version; the game needs three distinguishable forms.

   Ten verbs use the simple past rather than the perfect, because that is
   what people say: ich konnte, not ich habe können. They are marked prat.

   alt holds other time words that fit the same slot, so level two can
   replace gestern with letzte Woche without new content.

   past2 and past3 are harder versions of the same past card, on the
   thirteen verbs that take sein. past2 varies the person — she has heard
   ich bin a hundred times and du bist almost never. past3 adds structures
   she has not been taught: wegen des Regens is genitive, beim Aussteigen
   is a verb wearing a capital letter, spazieren gegangen is two verbs
   sharing one participle. That tier stays locked until she has earned it,
   because meeting the genitive by accident in an arcade game teaches
   nothing except that the game is unfair. */

