/* Dialogues.

   Ten conversations, eight lines each, four turns per speaker. Everyday
   situations chosen so that A1–A2 vocabulary and grammar recur across
   them rather than appearing once each: ordering, asking where something
   is, times, sizes, weather, changing an appointment.

   ------------------------------------------------------------------
   WHAT A DIALOGUE LOOKS LIKE

     id       dg-NN
     title    de / ru / en
     lines    an ordered list, one per line of the conversation

   A LINE

     w        which speaker, 'a' or 'b'. They alternate here, but the
              field is explicit rather than derived from the index —
              a three-speaker dialogue should not need this file's
              shape changed.
     de       the German, exactly as written
     ru       the Russian
     en       the English
     blank    the phrase to hide, per language, or absent

   ------------------------------------------------------------------
   THE BLANK IS A STRING, NOT AN INDEX

   `stories-long.js` carries `blanks` as word positions, which is fine
   until the same story exists in another language and position four is a
   different word. A phrase survives translation; a number does not. So a
   blank names the words:

     blank: { de:'Hafermilch', ru:'овсяное молоко' }

   A language with no key has no blank on that line, which is the right
   behaviour for a language where the phrase does not sit in one piece.

   The blanks are the ★ lines: chosen because the surrounding
   conversation gives her enough to reason the missing words out, rather
   than because the word happened to be worth testing. `Glaubst du, dass
   es regnen wird?` — `Schau dir diese dunklen ______ an.` is a
   comprehension question wearing a vocabulary exercise.

   ------------------------------------------------------------------
   ONE THING TO KNOW BEFORE USING THESE

   Six of the twenty German blanks have their own answer printed
   somewhere else in the same eight lines — `Hafermilch` is in line 2 and
   blanked in line 3. Whether that matters depends on whether the whole
   dialogue is on screen while she answers. If it is, those six are free.

   `seen` marks them, and it is PER LANGUAGE, because the two sets are not
   the same: six German blanks are visible elsewhere and only two Russian
   ones. `seen:{ de:true }` means the German answer is on screen and the
   Russian is not.

     seen: { de:true, ru:true }

   A blank must also appear verbatim in its own line, which is less
   obvious than it sounds. `карман куртки` looked like the Russian for
   `Jackentasche` and the line actually reads `карман своей куртки` — the
   words are not next to each other. Two more were written lower-case and
   sit at the start of their sentence. A checker catches all three; the
   eye does not. */

