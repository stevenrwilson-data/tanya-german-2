/* ---------- helpers ----------

   `cuesFor(lang)` is the load-bearing one: it returns the DISTINCT cue
   words for a language, in bin order, each carrying the list of bins it
   covers. English gets six entries, one of which covers three bins;
   German and Russian get eight, one bin each. The game builds its
   buttons from this and never asks which language it is in. */

window.GH_QUESTION_CUES.cuesFor = function(lang){
  var seen = {}, out = [];
  (this.bins || []).forEach(function(b){
    var word = b.cue[lang] || b.cue.en;
    if (seen[word] === undefined){
      seen[word] = out.length;
      out.push({ word:word, bins:[b.id] });
    } else {
      out[seen[word]].bins.push(b.id);
    }
  });
  return out;
};

/* The cue word a given bin wants in a given language. */
window.GH_QUESTION_CUES.cueFor = function(binId, lang){
  var hit = (this.bins || []).filter(function(b){ return b.id === binId; })[0];
  if (!hit) return '';
  return hit.cue[lang] || hit.cue.en;
};

window.GH_QUESTION_CUES.byBin = function(binId){
  return (this.items || []).filter(function(x){ return x.bin === binId; });
};

window.GH_QUESTION_CUES.item = function(id){
  var i, items = this.items || [];
  for (i = 0; i < items.length; i++) if (items[i].id === id) return items[i];
  return null;
};

window.GH_QUESTION_CUES.counts = function(){
  var c = {};
  (this.bins || []).forEach(function(b){ c[b.id] = 0; });
  (this.items || []).forEach(function(x){ if (c[x.bin] !== undefined) c[x.bin]++; });
  return c;
};

/* Does this bank have anything for a target language? The game asks this
   and hides itself if not, rather than carrying a hand-set language flag
   the way conveyor did — a flag drifts, a data check cannot. */
window.GH_QUESTION_CUES.hasLang = function(lang){
  var items = this.items || [];
  if (!items.length) return false;
  var bins = this.bins || [];
  if (!bins.length || !bins[0].cue[lang]) return false;
  var i;
  for (i = 0; i < items.length; i++){
    if (!items[i].st[lang] || !items[i].q[lang]) return false;
  }
  return true;
};
