/* Statements, and the question word each one answers.

   A statement contains an answer. The game shows the statement and asks
   which question word it answers: I went to the store → where.

   ------------------------------------------------------------------
   THE BINS ARE SEMANTIC, THE BUTTONS ARE PER LANGUAGE

   This is the whole design, and it is why one game serves every course.
   There are eight semantic bins. The number of BUTTONS is however many
   distinct cue words the current language has for them:

       bin          en        de       ru
       who          who       wer      кто
       what         what      was      что
       where        where     wo       где
       whereto      where     wohin    куда
       wherefrom    where     woher    откуда
       when         when      wann     когда
       why          why       warum    почему
       how          how       wie      как

   English uses `where` for three bins, so an English round shows SIX
   buttons and tapping `where` is correct for all three location bins.
   German and Russian distinguish them, so those rounds show EIGHT.

   The game therefore grades against the CUE LABEL, not the bin id, and
   builds its button list by collecting the distinct labels for the
   current target. Adding a language is one column in `bins` plus one
   field per item — no game code at all. If a game file ever contains
   `if (lang === 'de')`, that is the bug this shape exists to prevent.

   ------------------------------------------------------------------
   WHAT THIS FEEDS

   The game, and later the sentence-parts lesson, which is the same
   sentences from the other side: `who` is the semantic role, `subject`
   is the grammatical one, and *Max* in "Max found the keys" is both. A
   `part` field is reserved for that and deliberately unset — nobody
   should guess at it here.

   ------------------------------------------------------------------
   396 ITEMS, roughly fifty per bin, merged from three drafts on 09 Sep.
   Merged by script rather than by hand: deduped on the English
   statement (12 collisions, the existing row kept), Russian "X / Y"
   slash forms split into ru/ruM, and every id renumbered in bin order.

   ONE ROW WORTH KNOWING ABOUT. qc093 is "We are talking about school",
   whose German question is "Worüber sprechen wir?" — a wo-compound, not
   the plain `was`. The bin is still `what` and the button she taps is
   still `was`, so it grades correctly; she just sees a compound in the
   question that the button did not predict. Left in because the
   sentence is useful and the family is right. If more wo-compounds
   arrive (womit, wovon, worauf), they may deserve their own bins.

   ------------------------------------------------------------------
   CORRECTIONS TO THE SOURCE DRAFTS, 09 Sep

   1. GENDERED RUSSIAN. The draft wrote both forms in one string —
      "Я съел / съела яблоко". That is not how the site does it: `ru`
      holds the FEMININE form and `ruM` the masculine, and lessons.js
      and butler.js both pick between them. Six items and their
      questions were split accordingly. A statement about Max, Mila or
      Tanya is NOT twinned; only first and second person are.

   2. A GERMAN ERROR. "Ich habe nicht ans Telefon gegangen" — gehen
      takes sein. The draft's own question below it had it right
      ("Warum bist du nicht ans Telefon gegangen?"), so only the
      statement was wrong. Now "Ich bin nicht ans Telefon gegangen."

   3. THE ENGLISH CUE FOR ORIGIN. The draft gave "where / from where".
      English has six cue words, not seven — `from where` is not what an
      English speaker asks. It is `where`, and the question carries the
      preposition at the end: "Where did you come from?"

   4. THE CAST. Darrel, Pasadena and Palmdale are not in this world.
      Replaced with Max and German cities. The cast is Alina, Stella,
      Mila, Max, Sophie, Nazar, Dasha, Katya, Luna — plus Tanya, who is
      the learner's name rather than a character. Max is at school, so
      the "works in" item went to Katya. */

