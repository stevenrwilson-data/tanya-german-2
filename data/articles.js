/* ARTICLES — the fourth reading tier.

   Expository prose, where every other tier is narrative or verse. That is
   the point of it: an article is dense with nouns and plain statements,
   which is exactly the shape the vocabulary dumps produce and exactly what
   a story cannot carry. "Parmesan ist ein Hartkäse, den man über Pasta
   reiben kann" teaches a word in the only place it means anything.

   ------------------------------------------------------------------
   WHY A TIER AND NOT ITS OWN ACTIVITY

   The Reader's five-day translation rest is the mechanic worth keeping, and
   it only works because the WORD LIST is free while the translation is
   expensive. An article is precisely where she would reach for the
   translation, because it is dense with nouns she has never seen. Rebuilding
   that asymmetry elsewhere, or going without it, both cost more than adding
   a tier.

   Everything else comes free: the jump row is built from the section list,
   `reader-words.js` keys by piece id, and the question kinds are the ones
   already written.

   ------------------------------------------------------------------
   LONGER, AND PAID MORE

   26 lines against 12 for a medium story, so the tier is worth 25 and asks
   THREE questions rather than two — see reader.js SECTIONS.

   `tap` answers are ZERO-BASED indices into `sentences`. The source wrote
   them as 1-based line numbers; every one was converted with index = line-1
   and range-checked. An off-by-one does not throw, it silently marks the
   wrong line correct.

   ------------------------------------------------------------------
   ar-13 / ar-14 ARE NARRATIVE, NOT EXPOSITORY — AND THAT IS DELIBERATE

   Everything above describes what this tier was built for. Kitchen Wars
   (ar-13, the A1 Quick Read; ar-14, the B1 Full Story) is a story with
   named characters and dialogue — exactly what the opening paragraph
   says a story cannot carry. It lives here anyway, on Steven's call:
   `stories-short.js`/`stories-medium.js` are fixed-length, fixed-question-
   count tiers and cannot hold two different-length versions of one piece
   the way this file already proved out with the wine A2/B1 pair (ar-06/
   ar-07); `stories-long.js` requires `img`/`blanks` tied to Section 3
   vocabulary sheets, a mechanic this piece doesn't have. Nothing in the
   code enforces expository-only — that was a content-shape note, not a
   technical wall. If more narrative pieces like this arrive, revisit
   whether they still belong here or earn their own tier. */

/* ------------------------------------------------------------------
   `inL2:true` ON A QUESTION — what it means and when to set it

   The site teaches German. A question earns its place by moving that
   forward, and it can do so in one of two ways:

     needs the passage    she cannot answer without having understood the
                          German text. Leave it UNMARKED — translating the
                          question costs nothing, because the comprehension
                          already happened in the reading.

     prior knowledge      answerable by anyone, e.g. "which two fish are
                          popular for sushi?". Still a good question, but
                          only IN GERMAN: reading the question and its four
                          options is the whole exercise. Set `inL2:true`.

   Marked questions render in German whatever the interface language, with a
   button to translate that warns FIRST that the question will then not
   count. She may translate anyway; the other questions are unaffected.

   THE FLAG IS NOT A CRITICISM OF THE QUESTION. It says which of the two
   jobs it is doing.

   Currently 11 of 48. If a new article comes back with questions a learner
   could answer without reading it, the choice is: mark them, or rewrite
   them so they need the passage. Both are fine. What is NOT fine is leaving
   them unmarked, because then she scores full marks in English having read
   no German at all.
   ------------------------------------------------------------------ */

