/* Case: one preposition, two cases, decided by whether anything moves.

   Nine German prepositions take either case. Dative answers wo — where a
   thing is. Accusative answers wohin — where it is going. Nothing else in
   the sentence changes, which is why a matched pair is the only honest way
   to teach it:

     Die Katze ist auf dem Tisch.      position  -> dative
     Die Katze springt auf den Tisch.  motion    -> accusative

   Contractions are mandatory, not stylistic: in dem is im, an dem is am,
   von dem is vom, zu der is zur, bei dem is beim. That hides the article on
   the dative side for in and an, but the contrast survives and is closer to
   what she will hear — im Bus against in den Bus. The other seven two-way
   prepositions never contract, so auf dem against auf den still shows the
   bare case.

   One trap when adding more: a few verbs are welded to their preposition
   and always take accusative with no motion at all — warten auf, denken an,
   sich freuen auf. None appear here, and they must not.

   fixed[] is the easy level, where the case never varies:
     mit von zu bei nach aus seit  always dative
     für ohne durch gegen um       always accusative */

